/// Flat list "Area, State", Lagos and Abuja first, then states A–Z.
List<String> allNgLocations() {
  final states = ngLocationsByState.keys.toList();
  final rest = states.where((s) => s != 'Lagos' && s != 'Abuja (FCT)').toList()
    ..sort();
  return [
    for (final s in ['Lagos', 'Abuja (FCT)', ...rest])
      for (final a in ngLocationsByState[s]!)
        s == 'Abuja (FCT)' ? '$a, Abuja' : '$a, $s',
  ];
}
